/*
 * Notes:
 * The kernel works in depth (z down) and time convention e^{+iωt}, the frame of
 * Hunziker et al. (2015) and empymod. With s = (1, 1, -1), the PETGEM fields of
 * a moment p are E_a = s_a conj(E'_a(s p)) and H_a = -s_a conj(H'_a(s p)), with
 * E' and H' the kernel-frame fields. H of the electric source is computed by
 * reciprocity, as the electric field of a magnetic source with source and
 * receiver swapped. Kernels are labelled by the empymod ab codes: first digit
 * receiver, second digit source; 1-3 electric x, y, z; 4-6 magnetic x, y, z.
 * Filter coefficients: libdlf (BSD-3-Clause), key_201_2009.
 */

