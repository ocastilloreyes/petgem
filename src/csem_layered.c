/**
 * @brief Membership of a kernel code in a list of codes.
 *
 * @param[in] ab   Kernel code (empymod ab).
 * @param[in] set  List of codes.
 * @param[in] n    Number of codes in set.
 *
 * @return PetscBool PETSC_TRUE if ab is in set.
 */
static PetscBool inSet(PetscInt ab, const PetscInt set[], PetscInt n) {
  for (PetscInt i = 0; i < n; i++)
    if (set[i] == ab) return PETSC_TRUE;
  return PETSC_FALSE;
}

/**
 * @brief Layer that contains a depth.
 *
 * Layer n with depth[n] < zd <= depth[n + 1], with depth[numLayers] = +inf.
 *
 * @param[in] d   Dipole and layered model.
 * @param[in] zd  Depth (m, z down).
 *
 * @return PetscInt Layer index.
 */
static PetscInt layerOfDepth(const LayeredDipole *d, PetscReal zd) {
  PetscInt n = 0;
  while (n + 1 < d->numLayers && zd > d->depth[n + 1]) n++;
  return n;
}

/**
 * @brief Tests whether a depth lies on an interface.
 *
 * a lies on the interface at b when |a - b| <= LAYERED_INTERFACE_RTOL max(1,
 * |b|).
 *
 * @param[in] a  Depth (m).
 * @param[in] b  Interface depth (m).
 *
 * @return PetscBool PETSC_TRUE if a lies on the interface at b.
 */
static PetscBool onInterface(PetscReal a, PetscReal b) {
  return PetscAbsReal(a - b) <= LAYERED_INTERFACE_RTOL * PetscMax(1.0, PetscAbsReal(b)) ? PETSC_TRUE : PETSC_FALSE;
}

/**
 * @brief Tests whether a depth lies in a layer or on its boundary.
 *
 * @param[in] d   Dipole and layered model.
 * @param[in] n   Layer index.
 * @param[in] zd  Depth (m, z down).
 *
 * @return PetscBool PETSC_TRUE if zd lies in layer n or on one of its
 *         interfaces.
 */
static PetscBool inLayerClosure(const LayeredDipole *d, PetscInt n, PetscReal zd) {
  const PetscBool belowTop = (n == 0 || zd >= d->depth[n] || onInterface(zd, d->depth[n])) ? PETSC_TRUE : PETSC_FALSE;
  const PetscBool aboveBottom =
      (n + 1 == d->numLayers || zd <= d->depth[n + 1] || onInterface(zd, d->depth[n + 1])) ? PETSC_TRUE : PETSC_FALSE;
  return (belowTop && aboveBottom) ? PETSC_TRUE : PETSC_FALSE;
}

/**
 * @brief Vertical wavenumbers of the TM and TE modes in every layer.
 *
 * Gam[n] = sqrt(etaH/etaV lambda^2 + zeta etaH) (TM) and sqrt(lambda^2 + zeta
 * etaH) (TE).
 *
 * @param[in]  d       Dipole and layered model.
 * @param[in]  lambda  Horizontal wavenumber (1/m).
 * @param[out] GamTM   TM wavenumber per layer.
 * @param[out] GamTE   TE wavenumber per layer.
 */
static void computeGamma(const LayeredDipole *d, PetscReal lambda, PetscScalar GamTM[], PetscScalar GamTE[]) {
  const PetscReal l2 = lambda * lambda;
  for (PetscInt n = 0; n < d->numLayers; n++) {
    GamTM[n] = PetscSqrtScalar(d->etaH[n] / d->etaV[n] * l2 + d->zeta * d->etaH[n]);
    GamTE[n] = PetscSqrtScalar(l2 + d->zeta * d->etaH[n]);
  }
}

/**
 * @brief Reflection coefficients from below (Rp) and above (Rm) between the
 *        source and receiver layers.
 *
 * Port of empymod reflections.
 *
 * @param[in]  d     Dipole and layered model.
 * @param[in]  ezH   Mode parameter per layer (etaH for TM, zetaH for TE).
 * @param[in]  Gam   Vertical wavenumber of the mode per layer.
 * @param[in]  lrec  Receiver layer.
 * @param[in]  lsrc  Source layer.
 * @param[out] Rp    Reflection coefficients from below.
 * @param[out] Rm    Reflection coefficients from above.
 */
static void computeReflections(const LayeredDipole *d, const PetscScalar ezH[], const PetscScalar Gam[], PetscInt lrec, PetscInt lsrc,
                               PetscScalar Rp[], PetscScalar Rm[]) {
  const PetscInt nl = d->numLayers, maxl = PetscMax(lrec, lsrc), minl = PetscMin(lrec, lsrc);

  for (PetscInt k = 0; k < 2; k++) {
    const PetscBool plus   = (PetscBool)(k == 0);
    const PetscInt  pm     = plus ? 1 : -1;
    const PetscInt  minmax = plus ? maxl : -minl;
    PetscScalar    *Ref    = plus ? Rp : Rm;
    PetscScalar     tRef   = 0.0;
    PetscBool       any    = PETSC_FALSE;
    PetscInt        izout  = plus ? PetscAbsInt(lsrc - lrec) : 0;

    if ((lrec < lsrc && lrec == 0 && !plus) || (lrec > lsrc && lrec == nl - 1 && plus)) izout -= pm;
    for (PetscInt i = 0; i <= maxl - minl; i++) Ref[i] = 0.0;

    for (PetscInt iz = plus ? nl - 2 : 1; plus ? iz >= minl : iz <= maxl; iz -= pm) {
      const PetscScalar rloca = ezH[iz + pm] * Gam[iz], rlocb = ezH[iz] * Gam[iz + pm];
      const PetscScalar rloc = (rloca - rlocb) / (rloca + rlocb);

      if (!any) {
        tRef = rloc;
      } else {
        const PetscReal   ddepth = d->depth[iz + 1 + pm] - d->depth[iz + pm];
        const PetscScalar term   = tRef * PetscExpScalar(-2.0 * Gam[iz + pm] * ddepth);
        tRef                     = (rloc + term) / (1.0 + rloc * term);
      }
      any = PETSC_TRUE;
      if (lrec != lsrc && pm * iz <= minmax) {
        Ref[izout] = tRef;
        izout -= pm;
      }
    }
    if (lsrc == lrec && any) Ref[0] = tRef;
  }
}

/**
 * @brief Upgoing (Pu) and downgoing (Pd) fields at the receiver level.
 *
 * Port of empymod fields.
 *
 * @param[in]  d     Dipole and layered model.
 * @param[in]  Gam   Vertical wavenumber of the mode per layer.
 * @param[in]  Rp    Reflection coefficients from below.
 * @param[in]  Rm    Reflection coefficients from above.
 * @param[in]  lrec  Receiver layer.
 * @param[in]  lsrc  Source layer.
 * @param[in]  zsrc  Source depth (m, z down).
 * @param[in]  plus  Sign of the kernel group (KernelGroup.plus).
 * @param[out] Pu    Upgoing field.
 * @param[out] Pd    Downgoing field.
 */
static void computeUpDown(const LayeredDipole *d, const PetscScalar Gam[], const PetscScalar Rp[], const PetscScalar Rm[], PetscInt lrec,
                          PetscInt lsrc, PetscReal zsrc, PetscBool plus, PetscScalar *Pu, PetscScalar *Pd) {
  const PetscInt     nl = d->numLayers, nlsr = PetscAbsInt(lsrc - lrec) + 1, pm = plus ? 1 : -1;
  const PetscReal   *depth = d->depth;
  const PetscScalar  iGam  = Gam[lsrc];
  const PetscScalar *Rmp = Rm, *Rpm = Rp;
  PetscInt           rsrcl = 0, izStart = 2, izEnd = nlsr, isr = lsrc, last = nl - 1, pup = -1;
  PetscReal          mupm = 1.0, ds = 0.0, dp = 0.0, dm = zsrc - depth[lsrc];
  PetscBool          firstLayer = (PetscBool)(lsrc == 0), lastLayer = (PetscBool)(lsrc == nl - 1);

  if (lsrc != nl - 1) {
    ds = depth[lsrc + 1] - depth[lsrc];
    dp = depth[lsrc + 1] - zsrc;
  }
  *Pu = 0.0;
  *Pd = 0.0;

  for (PetscInt k = 0; k < 2; k++) {
    const PetscBool up = (PetscBool)(k == 1);
    PetscScalar     P;

    if (up && (lrec == nl - 1 || lrec > lsrc)) continue;
    if (!up && (lrec == 0 || lrec < lsrc)) continue;

    if (up) {
      const PetscScalar *t = Rmp;
      const PetscBool    f = firstLayer;
      if (!lastLayer) {
        const PetscReal s = dp;
        dp                = dm;
        dm                = s;
      } else {
        dp = dm;
      }
      Rmp        = Rpm;
      Rpm        = t;
      firstLayer = lastLayer;
      lastLayer  = f;
      rsrcl      = nlsr - 1;
      izStart    = 0;
      izEnd      = nlsr - 2;
      isr        = lrec;
      last       = 0;
      pup        = 1;
      if (!plus) mupm = -1.0;
    }

    if (lsrc == lrec) {
      if (lastLayer) {
        P = Rmp[0] * PetscExpScalar(-iGam * dm);
      } else {
        const PetscScalar p1 = PetscExpScalar(-iGam * dm);
        const PetscScalar p2 = (PetscReal)pm * Rpm[0] * PetscExpScalar(-iGam * (ds + dp));
        const PetscScalar p3 = 1.0 - Rmp[0] * Rpm[0] * PetscExpScalar(-2.0 * iGam * ds);
        P                    = (p1 + p2) * Rmp[0] / p3;
      }
    } else {
      const PetscScalar iRpm = Rpm[rsrcl];
      if (firstLayer) {
        P = (1.0 + iRpm) * mupm * PetscExpScalar(-iGam * dp);
      } else {
        const PetscScalar iRmp = Rmp[rsrcl];
        const PetscScalar p1   = mupm * PetscExpScalar(-iGam * dp);
        const PetscScalar p2   = (PetscReal)pm * mupm * iRmp * PetscExpScalar(-iGam * (ds + dm));
        const PetscScalar p3   = (1.0 + iRpm) / (1.0 - iRmp * iRpm * PetscExpScalar(-2.0 * iGam * ds));
        P                      = (p1 + p2) * p3;
      }
      if (up || lsrc + 1 < nl - 1) {
        const PetscReal ddepth = depth[lsrc + 1 - pup] - depth[lsrc - pup];
        if (!PetscIsInfOrNanReal(ddepth)) P /= 1.0 + Rpm[rsrcl - pup] * PetscExpScalar(-2.0 * Gam[lsrc - pup] * ddepth);
      }
      if (nlsr > 2) {
        for (PetscInt iz = izStart; iz < izEnd; iz++) {
          const PetscReal ddepth = depth[isr + iz + pup + 1] - depth[isr + iz + pup];
          P *= (1.0 + Rpm[iz + pup]) * PetscExpScalar(-Gam[isr + iz + pup] * ddepth);
          if (isr + iz != last) {
            const PetscReal dd = depth[isr + iz + 1] - depth[isr + iz];
            P /= 1.0 + Rpm[iz] * PetscExpScalar(-2.0 * Gam[isr + iz] * dd);
          }
        }
      }
    }
    if (up)
      *Pu = P;
    else
      *Pd = P;
  }
}

/**
 * @brief Reflection coefficients and up- and downgoing fields of one
 *        source-receiver arrangement for both modes.
 *
 * No-op for a single layer.
 *
 * @param[in]     d      Dipole and layered model.
 * @param[in]     zetaH  TE mode parameter per layer.
 * @param[in]     GamTM  TM wavenumber per layer.
 * @param[in]     GamTE  TE wavenumber per layer.
 * @param[in,out] a      Arrangement; its reflection coefficients and fields are
 *                       set here.
 */
static void computeArrangement(const LayeredDipole *d, const PetscScalar zetaH[], const PetscScalar GamTM[], const PetscScalar GamTE[],
                               Arrangement *a) {
  if (d->numLayers == 1) return;
  computeReflections(d, d->etaH, GamTM, a->lrec, a->lsrc, a->RpTM, a->RmTM);
  computeReflections(d, zetaH, GamTE, a->lrec, a->lsrc, a->RpTE, a->RmTE);
  computeUpDown(d, GamTM, a->RpTM, a->RmTM, a->lrec, a->lsrc, a->zsrc, PETSC_FALSE, &a->PuTMm, &a->PdTMm);
  computeUpDown(d, GamTM, a->RpTM, a->RmTM, a->lrec, a->lsrc, a->zsrc, PETSC_TRUE, &a->PuTMp, &a->PdTMp);
  computeUpDown(d, GamTE, a->RpTE, a->RmTE, a->lrec, a->lsrc, a->zsrc, PETSC_FALSE, &a->PuTEm, &a->PdTEm);
  computeUpDown(d, GamTE, a->RpTE, a->RmTE, a->lrec, a->lsrc, a->zsrc, PETSC_TRUE, &a->PuTEp, &a->PdTEp);
}

/**
 * @brief Green's function of one mode and kernel group, before the ab factors.
 *
 * Port of empymod greenfct.
 *
 * @param[in] d    Dipole and layered model.
 * @param[in] a    Source-receiver arrangement (computeArrangement).
 * @param[in] g    Kernel group.
 * @param[in] tm   PETSC_TRUE for the TM mode, PETSC_FALSE for TE.
 * @param[in] Gam  Vertical wavenumber of the mode per layer.
 *
 * @return PetscScalar Green's function at the receiver.
 */
static PetscScalar greenFunction(const LayeredDipole *d, const Arrangement *a, const KernelGroup *g, PetscBool tm,
                                 const PetscScalar Gam[]) {
  const PetscInt     nl      = d->numLayers;
  const PetscBool    plus    = tm ? g->plus : (PetscBool)!g->plus;
  const PetscScalar  lrecGam = Gam[a->lrec];
  const PetscScalar *Rp = tm ? a->RpTM : a->RpTE, *Rm = tm ? a->RmTM : a->RmTE;
  PetscScalar        Pu, Pd, Wu = 0.0, Wd = 0.0, green = 0.0;

  if (tm) {
    Pu = plus ? a->PuTMp : a->PuTMm;
    Pd = plus ? a->PdTMp : a->PdTMm;
  } else {
    Pu = plus ? a->PuTEp : a->PuTEm;
    Pd = plus ? a->PdTEp : a->PdTEm;
  }

  if (nl > 1) {
    if (a->lrec != nl - 1) Wu = PetscExpScalar(-lrecGam * (d->depth[a->lrec + 1] - a->zrec));
    if (a->lrec != 0) Wd = PetscExpScalar(-lrecGam * (a->zrec - d->depth[a->lrec]));
  }

  if (a->lsrc == a->lrec) {
    const PetscReal dz     = a->zrec - a->zsrc;
    PetscScalar     direct = PetscExpScalar(-lrecGam * PetscAbsReal(dz));

    if (nl > 1) green = g->srcMinus ? Pu * Wu - Pd * Wd : Pu * Wu + Pd * Wd;
    if (tm && g->tmMinus) direct = -direct;
    if (g->dsign) direct *= (dz > 0.0) ? 1.0 : ((dz < 0.0) ? -1.0 : 0.0);
    green += direct;
  } else {
    const PetscReal   ddepth = (a->lrec == nl - 1) ? 0.0 : d->depth[a->lrec + 1] - d->depth[a->lrec];
    const PetscScalar fexp   = PetscIsInfReal(ddepth) ? 0.0 : PetscExpScalar(-lrecGam * ddepth);
    const PetscReal   pmw    = (tm && g->tmMinus) ? -1.0 : 1.0;

    if (a->lrec < a->lsrc)
      green = Pu * (Wu + pmw * Rm[0] * fexp * Wd);
    else
      green = Pd * (pmw * Wd + Rp[PetscAbsInt(a->lsrc - a->lrec)] * fexp * Wu);
  }
  return green;
}

/**
 * @brief Adds the digital linear filter terms of a kernel at one filter point.
 *
 * J0 terms go to S0, J1 terms to S1 and the angle-dependent J0 terms to S0b
 * (empymod wavenumber).
 *
 * @param[in]     ab      Kernel code (empymod ab).
 * @param[in]     mrec    PETSC_TRUE for a magnetic receiver.
 * @param[in]     PTM     TM Green's function.
 * @param[in]     PTE     TE Green's function.
 * @param[in]     lambda  Horizontal wavenumber (1/m).
 * @param[in]     i       Filter point.
 * @param[in,out] S0      J0 sums.
 * @param[in,out] S1      J1 sums.
 * @param[in,out] S0b     Angle-dependent J0 sums.
 */
static void accumulateKernel(PetscInt ab, PetscBool mrec, PetscScalar PTM, PetscScalar PTE, PetscReal lambda, PetscInt i,
                             PetscScalar S0[3][6], PetscScalar S1[3][6], PetscScalar S0b[3][6]) {
  static const PetscInt setJ2[] = {11, 12, 21, 22, 14, 24, 15, 25}, setJ0[] = {11, 22, 24, 15}, setJ1[] = {13, 23, 31, 32, 34, 35, 16, 26};
  const PetscInt        r = ab / 10 - 1, c = ab % 10 - 1;
  const PetscScalar     Ptot = (PTM + PTE) / (4.0 * PETSC_PI);
  PetscReal             sign = mrec ? -1.0 : 1.0;

  if (inSet(ab, setJ2, 8)) {
    if (ab == 14 || ab == 22) sign = -sign;
    S0b[r][c] += sign / 2.0 * Ptot * lambda * key201J0[i];
    S1[r][c] += -sign * Ptot * key201J1[i];
    if (inSet(ab, setJ0, 4)) {
      if (ab == 22 || ab == 24) sign = -sign;
      S0[r][c] += (PTM - PTE) * lambda / (sign * 8.0 * PETSC_PI) * key201J0[i];
    }
  } else if (inSet(ab, setJ1, 8)) {
    if (ab == 34 || ab == 26) sign = -sign;
    S1[r][c] += sign * Ptot * lambda * lambda * key201J1[i];
  } else if (ab == 33) {
    S0[r][c] += sign * Ptot * lambda * lambda * lambda * key201J0[i];
  }
}

/**
 * @brief Angle factor of a kernel for the source-receiver azimuth.
 *
 * Port of empymod angle_factor; factors within round-off of zero are set to
 * zero.
 *
 * @param[in] angle  Source-receiver azimuth (rad).
 * @param[in] ab     Kernel code (empymod ab).
 * @param[in] mrec   PETSC_TRUE for a magnetic receiver.
 *
 * @return PetscReal Angle factor.
 */
static PetscReal angleFactor(PetscReal angle, PetscInt ab, PetscBool mrec) {
  static const PetscInt setCos[] = {11, 22, 15, 24, 13, 31, 26, 35}, setDouble[] = {11, 22, 15, 24, 12, 21, 14, 25};
  const PetscBool       useCos = inSet(ab, setCos, 8);
  const PetscReal       t1 = useCos ? PETSC_PI / 2.0 : PETSC_PI, t2 = useCos ? 3.0 * PETSC_PI / 2.0 : 2.0 * PETSC_PI;
  PetscReal             a = mrec ? angle + PETSC_PI : angle;

  if (ab == 33) return 1.0;
  if (inSet(ab, setDouble, 8)) a *= 2.0;
  if (PetscAbsReal(PetscAbsReal(a) - t1) <= 1.0e-14 + 1.0e-10 * t1) return 0.0;
  if (PetscAbsReal(PetscAbsReal(a) - t2) <= 1.0e-14 + 1.0e-10 * t2) return 0.0;
  return useCos ? PetscCosReal(a) : PetscSinReal(a);
}

/**
 * @brief Frequency-domain kernel from its digital linear filter sums at one
 *        offset.
 *
 * @param[in] ab     Kernel code (empymod ab).
 * @param[in] mrec   PETSC_TRUE for a magnetic receiver.
 * @param[in] r      Horizontal offset (m).
 * @param[in] angle  Source-receiver azimuth (rad).
 * @param[in] S0     J0 sums.
 * @param[in] S1     J1 sums.
 * @param[in] S0b    Angle-dependent J0 sums.
 *
 * @return PetscScalar Kernel ab at offset r.
 */
static PetscScalar transformKernel(PetscInt ab, PetscBool mrec, PetscReal r, PetscReal angle, PetscScalar S0[3][6], PetscScalar S1[3][6],
                                   PetscScalar S0b[3][6]) {
  static const PetscInt setJ2[] = {11, 12, 21, 22, 14, 24, 15, 25};
  const PetscInt        i = ab / 10 - 1, j = ab % 10 - 1;
  const PetscScalar     s1 = inSet(ab, setJ2, 8) ? S1[i][j] / r : S1[i][j];

  return ((s1 + S0b[i][j]) * angleFactor(angle, ab, mrec) + S0[i][j]) / r;
}

/**
 * @brief Fields of the dipole at a horizontal offset and a receiver depth, in
 *        the PETGEM frame.
 *
 * @param[in]     dipole  Dipole and layered model.
 * @param[in,out] w       Work arrays.
 * @param[in]     dx      Offset along x (m); the offset must be >=
 *                        LAYERED_MIN_OFFSET.
 * @param[in]     dy      Offset along y (m).
 * @param[in]     zrec    Receiver depth (m, z down).
 * @param[in]     lrec    Receiver layer.
 * @param[out]    E       Electric field.
 * @param[out]    H       Magnetic field, or NULL to skip it.
 */
static void evaluateOffset(const LayeredDipole *dipole, Workspace *w, PetscReal dx, PetscReal dy, PetscReal zrec, PetscInt lrec,
                           PetscScalar E[3], PetscScalar H[3]) {
  const PetscReal s[3]        = {1.0, 1.0, -1.0};
  const PetscReal pk[3]       = {dipole->moment[0], dipole->moment[1], -dipole->moment[2]};
  const PetscInt  kernE[3][3] = {{11, 12, 13}, {21, 22, 23}, {31, 32, 33}};
  const PetscReal r = PetscSqrtReal(dx * dx + dy * dy), angle = PetscAtan2Real(dy, dx);
  const PetscReal zsrc  = -dipole->position[2];
  const PetscInt  lsrc  = layerOfDepth(dipole, zsrc);
  PetscScalar    *GamTM = w->GamTM, *GamTE = w->GamTE, S0[3][6], S1[3][6], S0b[3][6], Ek[3], Hk[3];
  Arrangement    *aE = &w->aE, *aH = &w->aH;

  for (PetscInt i = 0; i < 3; i++)
    for (PetscInt j = 0; j < 6; j++) S0[i][j] = S1[i][j] = S0b[i][j] = 0.0;

  aE->zsrc = zsrc;
  aE->zrec = zrec;
  aE->lsrc = lsrc;
  aE->lrec = lrec;
  aH->zsrc = zrec;
  aH->zrec = zsrc;
  aH->lsrc = lrec;
  aH->lrec = lsrc;

  for (PetscInt i = 0; i < KEY201_SIZE; i++) {
    const PetscReal lambda = key201Base[i] / r;
    PetscScalar     gTM, gTE;

    computeGamma(dipole, lambda, GamTM, GamTE);

    /* Electric receiver: 11, 12, 21, 22; 13, 23; 31, 32; 33 */
    computeArrangement(dipole, w->zetaH, GamTM, GamTE, aE);
    gTM = greenFunction(dipole, aE, &group11, PETSC_TRUE, GamTM) * GamTM[lrec] / dipole->etaH[lrec];
    gTE = greenFunction(dipole, aE, &group11, PETSC_FALSE, GamTE) * dipole->zeta / GamTE[lsrc];
    accumulateKernel(11, PETSC_FALSE, gTM, gTE, lambda, i, S0, S1, S0b);
    accumulateKernel(12, PETSC_FALSE, gTM, gTE, lambda, i, S0, S1, S0b);
    accumulateKernel(21, PETSC_FALSE, gTM, gTE, lambda, i, S0, S1, S0b);
    accumulateKernel(22, PETSC_FALSE, gTM, gTE, lambda, i, S0, S1, S0b);

    gTM = -greenFunction(dipole, aE, &group13, PETSC_TRUE, GamTM) * dipole->etaH[lsrc] / dipole->etaH[lrec] / dipole->etaV[lsrc] *
          GamTM[lrec] / GamTM[lsrc];
    accumulateKernel(13, PETSC_FALSE, gTM, 0.0, lambda, i, S0, S1, S0b);
    accumulateKernel(23, PETSC_FALSE, gTM, 0.0, lambda, i, S0, S1, S0b);

    gTM = greenFunction(dipole, aE, &group31, PETSC_TRUE, GamTM) / dipole->etaV[lrec];
    accumulateKernel(31, PETSC_FALSE, gTM, 0.0, lambda, i, S0, S1, S0b);
    accumulateKernel(32, PETSC_FALSE, gTM, 0.0, lambda, i, S0, S1, S0b);

    gTM =
        greenFunction(dipole, aE, &group33, PETSC_TRUE, GamTM) * dipole->etaH[lsrc] / dipole->etaV[lsrc] / dipole->etaV[lrec] / GamTM[lsrc];
    accumulateKernel(33, PETSC_FALSE, gTM, 0.0, lambda, i, S0, S1, S0b);

    if (!H) continue;

    /* Magnetic receiver by reciprocity (source and receiver swapped): 14, 15, 24, 25; 16, 26; 34, 35 */
    computeArrangement(dipole, w->zetaH, GamTM, GamTE, aH);
    gTM = greenFunction(dipole, aH, &group14, PETSC_TRUE, GamTM) * dipole->etaH[aH->lsrc] / dipole->etaH[aH->lrec] * GamTM[aH->lrec] /
          GamTM[aH->lsrc];
    gTE = greenFunction(dipole, aH, &group14, PETSC_FALSE, GamTE);
    accumulateKernel(14, PETSC_TRUE, gTM, gTE, lambda, i, S0, S1, S0b);
    accumulateKernel(15, PETSC_TRUE, gTM, gTE, lambda, i, S0, S1, S0b);
    accumulateKernel(24, PETSC_TRUE, gTM, gTE, lambda, i, S0, S1, S0b);
    accumulateKernel(25, PETSC_TRUE, gTM, gTE, lambda, i, S0, S1, S0b);

    gTE = greenFunction(dipole, aH, &group16, PETSC_FALSE, GamTE) / GamTE[aH->lsrc];
    accumulateKernel(16, PETSC_TRUE, 0.0, gTE, lambda, i, S0, S1, S0b);
    accumulateKernel(26, PETSC_TRUE, 0.0, gTE, lambda, i, S0, S1, S0b);

    gTM = greenFunction(dipole, aH, &group34, PETSC_TRUE, GamTM) * dipole->etaH[aH->lsrc] / dipole->etaV[aH->lrec] / GamTM[aH->lsrc];
    accumulateKernel(34, PETSC_TRUE, gTM, 0.0, lambda, i, S0, S1, S0b);
    accumulateKernel(35, PETSC_TRUE, gTM, 0.0, lambda, i, S0, S1, S0b);
  }

  /* E'_a = sum_b K_ab p'_b; H'_a = sum_b K_(b, a+3) p'_b (ab 36 vanishes) */
  for (PetscInt a = 0; a < 3; a++) {
    Ek[a] = 0.0;
    Hk[a] = 0.0;
    for (PetscInt b = 0; b < 3; b++) {
      const PetscInt abH = 10 * (b + 1) + (a + 4);
      Ek[a] += transformKernel(kernE[a][b], PETSC_FALSE, r, angle, S0, S1, S0b) * pk[b];
      if (H && abH != 36) Hk[a] += transformKernel(abH, PETSC_TRUE, r, angle, S0, S1, S0b) * pk[b];
    }
  }
  for (PetscInt a = 0; a < 3; a++) {
    E[a] = s[a] * PetscConj(Ek[a]);
    if (H) H[a] = -s[a] * PetscConj(Hk[a]);
  }
}

/**
 * @brief Creates a layered model from per-layer arrays (copied).
 */
PetscErrorCode createLayeredModel(PetscInt numLayers, const PetscReal interfaces[], const PetscReal sigmaH[], const PetscReal sigmaV[],
                                  LayeredModel *model) {
  PetscFunctionBeginUser;

  PetscCheck(numLayers >= 1, PETSC_COMM_SELF, PETSC_ERR_ARG_OUTOFRANGE, "createLayeredModel: numLayers = %" PetscInt_FMT " (expected >= 1)",
             numLayers);
  for (PetscInt n = 0; n < numLayers - 1; n++) {
    PetscCheck(!PetscIsInfOrNanReal(interfaces[n]), PETSC_COMM_SELF, PETSC_ERR_ARG_OUTOFRANGE,
               "createLayeredModel: interface %" PetscInt_FMT " = %g is not finite", n, (double)interfaces[n]);
    PetscCheck(n == 0 || interfaces[n] < interfaces[n - 1], PETSC_COMM_SELF, PETSC_ERR_ARG_OUTOFRANGE,
               "createLayeredModel: interface %" PetscInt_FMT " = %g is not below interface %" PetscInt_FMT " = %g", n,
               (double)interfaces[n], n - 1, (double)interfaces[n - 1]);
  }
  for (PetscInt n = 0; n < numLayers; n++)
    PetscCheck(sigmaH[n] > 0.0 && sigmaV[n] > 0.0, PETSC_COMM_SELF, PETSC_ERR_ARG_OUTOFRANGE,
               "createLayeredModel: layer %" PetscInt_FMT " has sigmaH = %g, sigmaV = %g (expected > 0)", n, (double)sigmaH[n],
               (double)sigmaV[n]);

  model->numLayers = numLayers;
  PetscCall(PetscMalloc3(numLayers - 1, &model->interfaces, numLayers, &model->sigmaH, numLayers, &model->sigmaV));
  PetscCall(PetscArraycpy(model->interfaces, interfaces, numLayers - 1));
  PetscCall(PetscArraycpy(model->sigmaH, sigmaH, numLayers));
  PetscCall(PetscArraycpy(model->sigmaV, sigmaV, numLayers));

  PetscFunctionReturn(PETSC_SUCCESS);
}

/**
 * @brief Frees a model created by createLayeredModel().
 */
PetscErrorCode destroyLayeredModel(LayeredModel *model) {
  PetscFunctionBeginUser;
  PetscCall(PetscFree3(model->interfaces, model->sigmaH, model->sigmaV));
  model->numLayers = 0;
  PetscFunctionReturn(PETSC_SUCCESS);
}

/**
 * @brief Returns the layer that contains height z.
 */
PetscInt findLayer(const LayeredModel *model, PetscReal z) {
  PetscInt n = 0;
  while (n + 1 < model->numLayers && z < model->interfaces[n]) n++;
  return n;
}

/**
 * @brief Returns the layer that contains height z, taking the side of
 *        zSide on an interface.
 */
PetscInt findLayerOnSide(const LayeredModel *model, PetscReal z, PetscReal zSide) {
  const PetscInt n = findLayer(model, z);
  if (n > 0 && onInterface(z, model->interfaces[n - 1]) && zSide > model->interfaces[n - 1]) return n - 1;
  if (n + 1 < model->numLayers && onInterface(z, model->interfaces[n]) && zSide < model->interfaces[n]) return n + 1;
  return n;
}

/**
 * @brief Sets up an electric point dipole in a layered model.
 */
PetscErrorCode createLayeredDipole(const LayeredModel *model, PetscReal freq, const PetscReal position[3], const PetscReal moment[3],
                                   LayeredDipole *dipole) {
  PetscFunctionBeginUser;

  const PetscInt nl = model->numLayers;

  PetscCheck(freq > 0.0, PETSC_COMM_SELF, PETSC_ERR_ARG_OUTOFRANGE, "createLayeredDipole: frequency = %g (expected > 0)", (double)freq);

  dipole->numLayers = nl;
  PetscCall(PetscMalloc3(nl, &dipole->depth, nl, &dipole->etaH, nl, &dipole->etaV));
  for (PetscInt n = 0; n < nl; n++) {
    dipole->depth[n] = (n == 0) ? -(PetscReal)INFINITY : -model->interfaces[n - 1];
    dipole->etaH[n]  = model->sigmaH[n];
    dipole->etaV[n]  = model->sigmaV[n];
  }
  dipole->zeta = PETSC_i * angularFrequency(freq) * MU;
  for (PetscInt d = 0; d < 3; d++) {
    dipole->position[d] = position[d];
    dipole->moment[d]   = moment[d];
  }

  PetscFunctionReturn(PETSC_SUCCESS);
}

/**
 * @brief Evaluates E (and optionally H) of the dipole at points.
 */
PetscErrorCode evaluateLayeredDipole(const LayeredDipole *dipole, PetscInt numPoints, const PetscReal points[], const PetscInt layers[],
                                     PetscScalar E[], PetscScalar H[]) {
  PetscFunctionBeginUser;

  const PetscInt nl = dipole->numLayers;
  PetscScalar   *R;
  Workspace      w;

  for (PetscInt q = 0; q < numPoints; q++) {
    const PetscReal *x    = &points[q * 3];
    const PetscInt   lrec = layers ? layers[q] : layerOfDepth(dipole, -x[2]);
    PetscCheck(x[0] != dipole->position[0] || x[1] != dipole->position[1] || x[2] != dipole->position[2], PETSC_COMM_SELF,
               PETSC_ERR_ARG_OUTOFRANGE, "evaluateLayeredDipole: point %" PetscInt_FMT " coincides with the dipole", q);
    PetscCheck(lrec >= 0 && lrec < nl && inLayerClosure(dipole, lrec, -x[2]), PETSC_COMM_SELF, PETSC_ERR_ARG_OUTOFRANGE,
               "evaluateLayeredDipole: point %" PetscInt_FMT " at z = %g is outside layer %" PetscInt_FMT, q, (double)x[2], lrec);
  }

  PetscCall(PetscMemzero(&w, sizeof(w)));
  PetscCall(PetscMalloc4(nl, &w.GamTM, nl, &w.GamTE, nl, &w.zetaH, 8 * nl, &R));
  for (PetscInt n = 0; n < nl; n++) w.zetaH[n] = dipole->zeta;
  w.aE.RpTM = R;
  w.aE.RmTM = R + nl;
  w.aE.RpTE = R + 2 * nl;
  w.aE.RmTE = R + 3 * nl;
  w.aH.RpTM = R + 4 * nl;
  w.aH.RmTM = R + 5 * nl;
  w.aH.RpTE = R + 6 * nl;
  w.aH.RmTE = R + 7 * nl;

  for (PetscInt q = 0; q < numPoints; q++) {
    const PetscReal *x  = &points[q * 3];
    const PetscReal  dx = x[0] - dipole->position[0], dy = x[1] - dipole->position[1], dz = x[2] - dipole->position[2];
    const PetscReal  r    = PetscSqrtReal(dx * dx + dy * dy);
    const PetscReal  rc   = PetscMax(LAYERED_AXIS_RATIO * PetscAbsReal(dz), LAYERED_MIN_OFFSET);
    const PetscInt   lrec = layers ? layers[q] : layerOfDepth(dipole, -x[2]);
    PetscScalar     *Eq = &E[q * 3], *Hq = H ? &H[q * 3] : NULL;

    if (r >= rc) {
      evaluateOffset(dipole, &w, dx, dy, -x[2], lrec, Eq, Hq);
    } else {
      /* Lagrange interpolation from offsets +-rc, ..., +-LAYERED_AXIS_NODES rc along the azimuth of the point */
      const PetscReal ux = (r > 0.0) ? dx / r : 1.0, uy = (r > 0.0) ? dy / r : 0.0;
      PetscReal       sk[2 * LAYERED_AXIS_NODES];

      for (PetscInt k = 0; k < LAYERED_AXIS_NODES; k++) {
        sk[2 * k]     = (k + 1) * rc;
        sk[2 * k + 1] = -(k + 1) * rc;
      }
      for (PetscInt a = 0; a < 3; a++) {
        Eq[a] = 0.0;
        if (Hq) Hq[a] = 0.0;
      }
      for (PetscInt k = 0; k < 2 * LAYERED_AXIS_NODES; k++) {
        PetscScalar Ek[3], Hk[3];
        PetscReal   Lk = 1.0;

        for (PetscInt j = 0; j < 2 * LAYERED_AXIS_NODES; j++)
          if (j != k) Lk *= (r - sk[j]) / (sk[k] - sk[j]);
        evaluateOffset(dipole, &w, sk[k] * ux, sk[k] * uy, -x[2], lrec, Ek, Hq ? Hk : NULL);
        for (PetscInt a = 0; a < 3; a++) {
          Eq[a] += Lk * Ek[a];
          if (Hq) Hq[a] += Lk * Hk[a];
        }
      }
    }
  }

  PetscCall(PetscFree4(w.GamTM, w.GamTE, w.zetaH, R));
  PetscFunctionReturn(PETSC_SUCCESS);
}

/**
 * @brief Frees a dipole created by createLayeredDipole().
 */
PetscErrorCode destroyLayeredDipole(LayeredDipole *dipole) {
  PetscFunctionBeginUser;
  PetscCall(PetscFree3(dipole->depth, dipole->etaH, dipole->etaV));
  dipole->numLayers = 0;
  PetscFunctionReturn(PETSC_SUCCESS);
}
