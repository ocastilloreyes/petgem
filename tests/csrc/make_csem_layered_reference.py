def fields(case, point):
    """PETGEM-frame E and H at one point, interpolated near the dipole axis."""
    d = np.asarray(point, float) - np.asarray(case["position"], float)
    r, rc = np.hypot(d[0], d[1]), max(4e-2 * abs(d[2]), 1e-3)
    if r >= rc:
        return offsetFields(case, point)
    u = d[:2] / r if r > 0 else np.array([1.0, 0.0])
    sk = rc * np.array([1.0, -1.0, 2.0, -2.0, 3.0, -3.0, 4.0, -4.0])
    E, H = np.zeros(3, complex), np.zeros(3, complex)
    for k in range(sk.size):
        Lk = np.prod([(r - sk[j]) / (sk[k] - sk[j]) for j in range(sk.size) if j != k])
        Ek, Hk = offsetFields(case, [case["position"][0] + sk[k] * u[0], case["position"][1] + sk[k] * u[1], point[2]])
        E, H = E + Lk * Ek, H + Lk * Hk
    return E, H


def offsetFields(case, point):
    """PETGEM-frame E and H at one point."""
    depth = [-z for z in case["interfaces"]]
    sh, sv = np.array(case["sigmaH"]), np.array(case["sigmaV"])
    zeros = np.zeros(sh.size)
    kw = dict(depth=depth, res=1.0 / sh, aniso=np.sqrt(sh / sv), freqtime=case["freq"], epermH=zeros, epermV=zeros,
              xdirect=False, ht="dlf", htarg={"dlf": "key_201_2009", "pts_per_dec": 0}, verb=0)
    src = [case["position"][0], case["position"][1], -case["position"][2]]
    rec = [point[0], point[1], -point[2]]
    pk = S * np.asarray(case["moment"])
    Ek, Hk = np.zeros(3, complex), np.zeros(3, complex)
    for a in range(3):
        for b in range(3):
            Ek[a] += complex(empymod.dipole(src, rec, ab=10 * (a + 1) + (b + 1), **kw)) * pk[b]
            if (a, b) != (2, 2):
                Hk[a] += complex(empymod.dipole(src, rec, ab=10 * (a + 4) + (b + 1), **kw)) * pk[b]
    return S * np.conj(Ek), -S * np.conj(Hk)


def cArray(values):
    return "{" + ", ".join(repr(float(v)) for v in values) + "}"


def main():
    maxLayers = max(len(c["sigmaH"]) for c in CASES)
    maxPoints = max(len(c["points"]) for c in CASES)
    out = [f"/* Generated by tests/csrc/make_csem_layered_reference.py (empymod {empymod.__version__}); do not edit. */",
           "#ifndef CSEM_LAYERED_REFERENCE_H", "#define CSEM_LAYERED_REFERENCE_H", "",
           f"#define LR_MAX_LAYERS {maxLayers}", f"#define LR_MAX_POINTS {maxPoints}", "",
           "/* Layered model, dipole and PETGEM-frame fields: E[q][d] = {re, im}. */",
           "typedef struct {", "  const char *name;", "  PetscInt    numLayers;",
           "  PetscReal   interfaces[LR_MAX_LAYERS];", "  PetscReal   sigmaH[LR_MAX_LAYERS];",
           "  PetscReal   sigmaV[LR_MAX_LAYERS];", "  PetscReal   freq;", "  PetscReal   position[3];",
           "  PetscReal   moment[3];", "  PetscInt    numPoints;", "  PetscReal   points[LR_MAX_POINTS][3];",
           "  PetscReal   E[LR_MAX_POINTS][3][2];", "  PetscReal   H[LR_MAX_POINTS][3][2];", "} LayeredReference;", "",
           "static const LayeredReference layeredReference[] = {"]
    for case in CASES:
        E, H = zip(*(fields(case, p) for p in case["points"]))
        pts = ", ".join(cArray(p) for p in case["points"])
        cE = ", ".join("{" + ", ".join(cArray([v.real, v.imag]) for v in e) + "}" for e in E)
        cH = ", ".join("{" + ", ".join(cArray([v.real, v.imag]) for v in h) + "}" for h in H)
        out += ["    {", f'     "{case["name"]}",', f"     {len(case['sigmaH'])},",
                f"     {cArray(case['interfaces'] or [0.0])},", f"     {cArray(case['sigmaH'])},",
                f"     {cArray(case['sigmaV'])},", f"     {case['freq']!r},", f"     {cArray(case['position'])},",
                f"     {cArray(case['moment'])},", f"     {len(case['points'])},", f"     {{{pts}}},",
                f"     {{{cE}}},", f"     {{{cH}}},", "    },"]
    out += ["};", "", "#endif /* CSEM_LAYERED_REFERENCE_H */", ""]
    path = Path(__file__).resolve().parent / "csem_layered_reference.h"
    path.write_text("\n".join(out))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
