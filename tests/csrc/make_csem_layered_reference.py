"""Writes tests/csrc/csem_layered_reference.h for test_csem_layered.c.

E and H of an electric point dipole in layered VTI models, computed with
empymod (key_201_2009 filter, direct field in the wavenumber domain, no
displacement currents) and converted to the PETGEM frame (z up, e^{-iwt}):
E_a = s_a conj(E'_a(s p)), H_a = -s_a conj(H'_a(s p)), s = (1, 1, -1).
Points with horizontal offset r < r_c = max(0.04 |z - z_s|, 1e-3) use the
interpolation of csem_layered.c from the offsets +-r_c, ..., +-4r_c.

Usage (needs empymod):
    python3 tests/csrc/make_csem_layered_reference.py
"""
from pathlib import Path

import empymod
import numpy as np

S = np.array([1.0, 1.0, -1.0])


def direction(azimuth, dip):
    a, b = np.radians(azimuth), np.radians(dip)
    return np.array([np.cos(a) * np.cos(b), np.sin(a) * np.cos(b), np.sin(b)])


