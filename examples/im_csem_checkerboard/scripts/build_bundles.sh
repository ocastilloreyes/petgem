#!/usr/bin/env bash

# ============================================================================
# CSEM inversion benchmark (im_csem_checkerboard): input bundles
#
# This script calls the general preprocessor utils/preprocess.py with the
# mesh, survey and conductivity files of this benchmark and writes the HDF5
# bundles read by the PETGEM solvers. It has two stages:
#   fm  Seven forward bundles on the true model (geometry/mesh_true.msh),
#       one per frequency
#   im  One inverse bundle with the starting model (geometry/mesh.msh) and
#       the observed data
#
# Usage (from the repository root):
#   bash examples/im_csem_checkerboard/scripts/build_bundles.sh <fm|im>
#
#   With the petgem-env image:
#   docker run --rm -u $(id -u):$(id -g) -v "$PWD":/workspace -w /workspace \
#       petgem-env:latest bash examples/im_csem_checkerboard/scripts/build_bundles.sh <fm|im>
#
# Required input:
#   fm  survey/ and geometry/ files of the true model
#   im  outputs/observed.h5
#         Generated by scripts/make_observations.sh
#
# Generated output:
#   fm  outputs/input_fm_f<F>.h5
#   im  outputs/input_im.h5
#
# Notes:
#   - Requires numpy, meshio, h5py and petsc4py (all in petgem-env).
#   - No observed dataset is shipped. The benchmark is meant to be run end to
#     end, so the inversion always uses the observations of the current run.
#   - Set OBSERVED=<path>, relative to the case directory, to use another
#     observations file.
# ============================================================================

CASE_DIR=examples/im_csem_checkerboard exec bash examples/shared/inversion_bundles.sh "$@"
